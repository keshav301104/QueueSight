"""Turn a simulation run into the same 4 CSV files as the DATATHON dataset, so the whole pipeline works unchanged.
One deliberate difference: patients who left before care have no service times (the original data had them)."""
from pathlib import Path

import numpy as np
import pandas as pd

from sim.config import TRIAGE_LEVELS
from sim.engine import SimResult

TS_FMT = "%Y-%m-%d %H:%M:%S"


def _clock(start: pd.Timestamp, minutes: pd.Series) -> pd.Series:
    """Minutes-from-start -> wall-clock timestamps, rounded to the whole minute (like real hospital systems)."""
    return start + pd.to_timedelta(minutes.round(), unit="min")


def to_tables(result: SimResult) -> dict[str, pd.DataFrame]:
    cfg, v = result.config, result.visits
    start = pd.Timestamp(cfg.start_date)
    order = v.sort_values("arrival", kind="stable").index
    v = v.loc[order]
    enc_ids = pd.Series([f"E{i:06d}" for i in range(1, len(v) + 1)], index=v.index)

    arrival = _clock(start, v["arrival"])
    svc_start = _clock(start, v["start"])            # NaT for walk-outs
    svc_end = _clock(start, v["end"])
    discharge = _clock(start, v["discharge"])
    left = _clock(start, v["left"])
    wait_end = svc_start.fillna(left)
    seen = svc_start.notna()

    encounters = pd.DataFrame({
        "encounter_id": enc_ids,
        "patient_id": result.population["patient_id"].to_numpy()[v["patient_idx"]],
        "arrival_time": arrival,
        "department_id": [cfg.departments[d].id for d in v["dept_idx"]],
        "visit_type": v["visit_type"],
        "triage_level": np.asarray(TRIAGE_LEVELS)[v["triage"]],
        "outcome": v["outcome"],
        "service_start_time": svc_start,
        "service_end_time": svc_end,
        # computed from the rounded timestamps so the minutes always match the times exactly
        "wait_minutes": ((wait_end - arrival).dt.total_seconds() / 60).round().astype(int),
        "service_minutes": ((svc_end - svc_start).dt.total_seconds() / 60).round().astype("Int64"),
        "discharge_time": discharge.where(seen, wait_end),
    })

    t = result.tests.sort_values("requested", kind="stable")
    tests = pd.DataFrame({
        "test_id": [f"T{i:06d}" for i in range(1, len(t) + 1)],
        "encounter_id": enc_ids.loc[t["visit_idx"]].to_numpy(),
        "test_type": t["test_type"].to_numpy(),
        "requested_time": _clock(start, t["requested"]).to_numpy(),
        "completion_time": _clock(start, t["completed"]).to_numpy(),
        "priority": t["priority"].to_numpy(),
    })

    departments = pd.DataFrame([{
        "department_id": d.id,
        "department_name": d.name,
        "staff_count": max(d.shifts.values()),
        "bed_count": d.bed_count,
        # realistic capacity: clinician-minutes per weekday / typical consultation length
        "daily_capacity": int(sum(s * _shift_len(d.shifts, h) for h, s in d.shifts.items()) * 60 / d.service_median_min),
        "service_type": d.service_type,
    } for d in cfg.departments])

    patients = result.population.drop(columns="visit_weight")
    return {"patients": patients, "encounters": encounters.reset_index(drop=True),
            "departments": departments, "diagnostic_tests": tests}


def _shift_len(shifts: dict[int, int], hour: int) -> int:
    hours = sorted(shifts)
    nxt = hours[(hours.index(hour) + 1) % len(hours)]
    return (nxt - hour) % 24 or 24


def write_csvs(tables: dict[str, pd.DataFrame], out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, df in tables.items():
        df.to_csv(out_dir / f"{name}.csv", index=False, date_format=TS_FMT)
    (out_dir / "README.txt").write_text(
        "QUEUESIGHT SIMULATED HOSPITAL\n"
        "Generated by backend/sim (discrete-event simulation). Not real patient data.\n"
        "Same files and columns as the DATATHON 2026 Track 1 dataset. Patients who left before care\n"
        "have no service start/end times; their wait_minutes is how long they waited before leaving.\n"
    )